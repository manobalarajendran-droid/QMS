export function computeNextRevision(currentRev?: string): string {
  if (!currentRev) return 'Rev 01';
  const match = currentRev.match(/\d+/);
  if (!match) return `${currentRev} A`;
  const nextNum = parseInt(match[0], 10) + 1;
  return `Rev ${String(nextNum).padStart(2, '0')}`;
}

